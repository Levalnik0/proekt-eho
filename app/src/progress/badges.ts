/**
 * Медали.
 *
 * Правила формулировок — они важнее кода:
 * 1. Название медали описывает ДЕЙСТВИЕ, а не качество человека.
 *    «Взял паузу», а не «Терпеливый родитель».
 * 2. Нет медалей «за неправильно». Даже тяжёлый финал даёт медаль за опыт.
 * 3. Взрослому никогда не говорим «вы не знаете ребёнка».
 *    Показываем расхождение — вывод он делает сам.
 * 4. Каждая медаль взрослого несёт `growth` — ОДНО маленькое действие,
 *    а не список претензий. Формулировка «попробуйте», а не «вам нужно».
 */

export type Role = 'teen' | 'adult';

/** Картинку медали задаёт MEDAL_GLYPH в MedalIcon.tsx */
